#!/usr/bin/env node
/*
 * Brand book build.
 * Reads the BRAND and GUIDE data from index.html and regenerates:
 *   tokens/tokens.json, tokens/tokens.css, tokens/components.css,
 *   assets/icons/*.svg, docs/**.md and CHANGE-HISTORY.md
 * so the HTML, the tokens and the docs never drift apart.
 *
 * Usage (from the book folder):  node tools/build.js
 * Needs Node 16 or later. No packages to install.
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
const grab = (id) => {
  const m = html.match(new RegExp('<script id="' + id + '">([\\s\\S]*?)</script>'));
  if (!m) throw new Error("Missing <script id=\"" + id + "\"> in index.html");
  return m[1];
};
const ctx = {};
vm.createContext(ctx);
vm.runInContext(grab("brand-data") + "\n" + grab("guide-data") + "\nthis.BRAND = BRAND; this.GUIDE = GUIDE;", ctx);
const B = ctx.BRAND, G = ctx.GUIDE;

const write = (rel, text) => {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
  return rel;
};
const out = [];

/* ---------- Tokens ---------- */
const prim = {};
B.primitives.forEach(([, items]) => items.forEach(([n, v]) => (prim[n] = v)));
const ref = (v) => (prim[v] ? `var(--${v})` : v);

const tokensJson = {
  name: B.name, version: B.version, updated: B.updated,
  primitives: Object.fromEntries(B.primitives.map(([g, items]) => [g.toLowerCase(), Object.fromEntries(items)])),
  semantic: {
    light: Object.fromEntries(B.semantic.flatMap(([, items]) => items.map(([n, l]) => [n, prim[l] ? `{${l}}` : l]))),
    dark: Object.fromEntries(B.semantic.flatMap(([, items]) => items.map(([n, , d]) => [n, prim[d] ? `{${d}}` : d])))
  },
  usage: Object.fromEntries(B.semantic.flatMap(([, items]) => items.map(([n, , , u]) => [n, u]))),
  font: { display: B.fonts.display.stack, body: B.fonts.body.stack },
  type: Object.fromEntries(B.type.map(([n, fam, d, m, lh, w, ls]) => [n, { family: fam, size: d, sizeMobile: m, lineHeight: lh, weight: w, letterSpacing: ls }])),
  spacing: Object.fromEntries(B.spacing.map(([n, v]) => [n, v + "px"])),
  radius: Object.fromEntries(B.radius.map(([n, v]) => [n, v])),
  shadow: { light: Object.fromEntries(B.shadows.map(([n, l]) => [n, l])), dark: Object.fromEntries(B.shadows.map(([n, , d]) => [n, d])) },
  motion: { easing: Object.fromEntries(B.motion.curves.map(([n, c]) => [n, n === "linear" ? "linear" : `cubic-bezier(${c})`])), duration: Object.fromEntries(B.motion.durations.map(([ms, u]) => [u, ms + "ms"])) }
};
out.push(write("tokens/tokens.json", JSON.stringify(tokensJson, null, 2)));

let css = `/* ${B.name} tokens v${B.version}. Generated by tools/build.js from index.html. Do not edit by hand. */\n`;
["display", "body"].forEach((k) => {
  const f = B.fonts[k];
  if (f.src) css += `@font-face { font-family: "${f.family}"; src: url("../${f.src}") format("woff2"); font-weight: ${f.weights}; font-display: swap; }\n`;
});
css += "\n:root {\n  /* Primitives */\n";
B.primitives.forEach(([, items]) => items.forEach(([n, v]) => (css += `  --${n}: ${v};\n`)));
css += "\n  /* Semantic: light */\n";
B.semantic.forEach(([, items]) => items.forEach(([n, l]) => (css += `  --${n}: ${ref(l)};\n`)));
css += "\n  /* Type */\n";
css += `  --font-display: ${B.fonts.display.stack};\n  --font-body: ${B.fonts.body.stack};\n`;
css += "\n  /* Spacing */\n";
B.spacing.forEach(([n, v]) => (css += `  --${n}: ${v}px;\n`));
css += "\n  /* Radius */\n";
B.radius.forEach(([n, v]) => (css += `  --${n}: ${v};\n`));
css += "\n  /* Shadow */\n";
B.shadows.forEach(([n, l]) => (css += `  --${n}: ${l};\n`));
css += "\n  /* Motion */\n";
B.motion.curves.forEach(([n, c]) => (css += `  --${n}: ${n === "linear" ? "linear" : `cubic-bezier(${c})`};\n`));
css += "}\n\n[data-theme=\"dark\"] {\n";
B.semantic.forEach(([, items]) => items.forEach(([n, , d]) => (css += `  --${n}: ${ref(d)};\n`)));
B.shadows.forEach(([n, , d]) => (css += `  --${n}: ${d};\n`));
css += "  color-scheme: dark;\n}\n\n/* Text styles */\n";
B.type.forEach(([n, fam, d, m, lh, w, ls]) => {
  css += `.${n} { font-family: var(--font-${fam}); font-size: ${d}px; line-height: ${lh}; font-weight: ${w}; letter-spacing: ${ls}; }\n`;
});
css += "@media (max-width: 767px) {\n";
B.type.forEach(([n, , d, m]) => { if (m !== d) css += `  .${n} { font-size: ${m}px; }\n`; });
css += "}\n";
out.push(write("tokens/tokens.css", css));

const ds = html.match(/\/\* ds:start \*\/([\s\S]*?)\/\* ds:end \*\//);
out.push(write("tokens/components.css", `/* ${B.name} components v${B.version}. Generated by tools/build.js from index.html. Requires tokens.css. */\n` + ds[1].replace(/^\.p \{/m, "body {").trim()));

/* ---------- Icons ---------- */
const svg = (n) => `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${G.icons[n]}</svg>\n`;
fs.mkdirSync(path.join(ROOT, "assets/icons"), { recursive: true });
Object.keys(G.icons).forEach((n) => fs.writeFileSync(path.join(ROOT, "assets/icons", n + ".svg"), svg(n)));
fs.writeFileSync(path.join(ROOT, "assets/icons/sprite.svg"), `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${Object.keys(G.icons).map((n) => `  <symbol id="icon-${n}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${G.icons[n]}</symbol>`).join("\n")}\n</svg>\n`);
out.push(`assets/icons/ (${Object.keys(G.icons).length} icons + sprite.svg)`);

/* ---------- Docs ---------- */
const md = {
  table: (h, rows) => `| ${h.join(" | ")} |\n| ${h.map(() => "---").join(" | ")} |\n` + rows.map((r) => `| ${r.map((c) => String(c).replace(/\|/g, "\\|")).join(" | ")} |`).join("\n") + "\n",
  list: (a) => a.map((t) => `- ${t}`).join("\n") + "\n",
  head: (n, t, lead) => `# ${n} · ${t}\n\n${lead}\n\n_${B.name} Brand Book v${B.version} · generated from index.html_\n`
};
const O = B.overview, V = B.voice, L = B.logo;

out.push(write("docs/brand/01-overview.md", `${md.head("01", "Overview", `What ${B.name} is about, who we speak to, and the principles and personality behind every decision.`)}
## What ${B.name} is about

${O.about.join("\n\n")}

${md.table(["Product", "What it does"], O.offer)}
## Who we speak to

${md.table(["Audience", "What they want from us"], O.audiences)}
## Principles

${O.principles.map(([t, d], i) => `${i + 1}. **${t}.** ${d}`).join("\n")}

## Personality

${md.table(["We are", "We are not"], O.personality)}`));

out.push(write("docs/brand/02-voice-and-writing.md", `${md.head("02", "Voice and writing", V.summary)}
## Our voice

${md.table(["Trait", "What it means"], V.traits)}
## Tone by situation

The voice stays the same. The tone changes with what the reader is doing.

${md.table(["Situation", "How it sounds", "Example", "Why it works"], V.situations)}
## Writing principles

**Do**

${md.list(V.do)}
**Don't**

${md.list(V.dont)}
## ${V.care.title}

${md.list(V.care.rules)}
## UI writing patterns

${md.table(["Element", "Pattern", "Write", "Not", "Why it works"], V.ui)}
## Word list

${md.table(["Use", "Avoid", "Why"], V.terms)}
## Length guide

${md.table(["Element", "Aim for", "Limit"], G.lengthGuide)}
## Before you publish

${md.list(G.contentChecks)}`));

out.push(write("docs/brand/03-logo.md", `${md.head("03", "Logo", "Use the supplied file at its original proportions, every time.")}
## Clear space

${L.clearSpace}

## Minimum size

${md.table(["Height", "Use"], L.sizes.map(([px, u]) => [px + " px", u]))}
## Approved backgrounds

${md.table(["Background", "Hex"], L.backgrounds)}
## Never

${md.list(L.never)}
## Files

${md.table(["File", "Format", "Use"], L.files.map((f) => [f[3] ? `[${f[0]}](../../${f[3]})` : f[0], f[1], f[2]]))}
${L.note || ""}`));

out.push(write("docs/foundations/04-colour.md", `${md.head("04", "Colour", "Primitives are the raw palette. Semantic tokens give each colour a job. Designs and code use semantic tokens only.")}
## Core colours

${md.table(["Name", "Token", "Value"], B.core.map(([n, t]) => { const s = B.semantic.flatMap((g) => g[1]).find((x) => x[0] === t); return [n, `\`${t}\``, prim[s[1]] || s[1]]; }))}
## Semantic tokens

${B.semantic.map(([g, items]) => `### ${g}\n\n${md.table(["Token", "Light", "Dark", "Use"], items.map(([n, l, d, u]) => [`\`${n}\``, prim[l] ? `${l} (${prim[l]})` : l, prim[d] ? `${d} (${prim[d]})` : d, u]))}`).join("\n")}
## Primitive palette

${B.primitives.map(([g, items]) => `### ${g}\n\n${md.table(["Primitive", "Hex"], items.map(([n, v]) => [`\`${n}\``, v]))}`).join("\n")}
## Rules

**Do**

${md.list(B.colourRules.do)}
**Don't**

${md.list(B.colourRules.dont)}`));

out.push(write("docs/foundations/05-typography.md", `${md.head("05", "Typography", "Two typefaces and one scale for web and product.")}
## Typefaces

${md.table(["Role", "Family", "Weights", "Source"], ["display", "body"].map((k) => [B.fonts[k].role, B.fonts[k].family, B.fonts[k].weights.replace(" ", "–"), B.fonts[k].source + (B.fonts[k].src ? ` (\`${B.fonts[k].src}\`)` : "")]))}
## Scale

${md.table(["Style", "Family", "Size (desktop / mobile)", "Line height", "Weight", "Tracking"], B.type.map(([n, f, d, m, lh, w, ls]) => [`\`${n}\``, f, d === m ? `${d}` : `${d} / ${m}`, lh, w, ls]))}
## Rules

**Do**

${md.list(B.typeRules.do)}
**Don't**

${md.list(B.typeRules.dont)}`));

out.push(write("docs/foundations/06-spacing-and-layout.md", `${md.head("06", "Spacing and layout", `A 4 px spacing scale and a 12-column grid capped at ${B.layout.max}.`)}
## Spacing scale

${md.table(["Token", "Value"], B.spacing.map(([n, v]) => [`\`${n}\``, v + " px"]))}
## Grid

${md.table(["Breakpoint", "Width", "Columns", "Side gutter", "Section padding"], B.layout.grid)}
## Web and mobile

What is shared across platforms, and what is intentionally different.

${md.table(["Area", "Shared", "Web", "Mobile"], G.platforms)}`));

out.push(write("docs/foundations/07-radius-and-elevation.md", `${md.head("07", "Radius and elevation", "Corner radius, borders and shadows, and the rule for when to use each.")}
## Radius

${md.table(["Token", "Value", "Use"], B.radius.map(([n, v, u]) => [`\`${n}\``, v, u]))}
## Surface rule

${B.surfaceRule}

## Shadows

${md.table(["Token", "Light", "Dark", "Use"], B.shadows.map(([n, l, d, u]) => [`\`${n}\``, `\`${l}\``, `\`${d}\``, u]))}
## Borders

${md.table(["Use", "Token", "Width"], [["Card edge", "`ring`", "1 px"], ["Divider", "`line`", "1 px"], ["Controls", "`line-strong`", "1 px"], ["Focus ring", "`focus`", "2 px, 2–3 px offset"]])}`));

out.push(write("docs/foundations/08-iconography.md", `${md.head("08", "Iconography", "One line-icon set on a 24 px grid: 2 px stroke, round caps and joins, currentColor.")}
Files: \`assets/icons/<name>.svg\` and \`assets/icons/sprite.svg\` (use as \`<svg><use href="sprite.svg#icon-check"/></svg>\`).

Sizes: 16 px in buttons, 20 px in lists and alerts, 24 px on its own.

${md.table(["Icon", "File"], Object.keys(G.icons).map((n) => [n, `[${n}.svg](../../assets/icons/${n}.svg)`]))}`));

out.push(write("docs/foundations/09-motion.md", `${md.head("09", "Motion", "Smooth and unhurried. Motion guides the eye and never performs.")}
## Easing

${md.table(["Name", "Value", "Use"], B.motion.curves.map(([n, c, u]) => [`\`${n}\``, n === "linear" ? "linear" : `cubic-bezier(${c})`, u]))}
## Durations

${md.table(["Duration", "Use"], B.motion.durations.map(([ms, u]) => [ms + " ms", u]))}
Under reduced motion, everything renders in its final state.`));

const META = (id) => (B.components && B.components[id]) || { version: "0.1.0", status: "Draft", log: [["0.1.0", B.updated, "Added from the template"]] };
const LIB = B.library || { version: "0.1.0", updated: B.updated };
out.push(write("docs/components/10-components.md", `${md.head("10", "Components", "The full component library. Every component lists its version, status and change log, then purpose, anatomy, variants, states, behaviour, tokens and usage. Styles: `tokens/components.css`.")}
## Library

Library v${LIB.version} · ${G.components.length} components · updated ${LIB.updated}. Versions follow major.minor.patch: major for breaking changes, minor for additions, patch for fixes.

${md.table(["Component", "Category", "Version", "Status", "Updated"], G.components.map((c) => { const m = META(c.id); return [`[${c.name}](#${c.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")})`, c.cat, m.version, m.status, m.log[0][1]]; }))}
${G.components.map((c) => { const m = META(c.id); return `## ${c.name}

\`v${m.version}\` · ${m.status} · ${c.cat}

${c.purpose}

${md.table(["", ""], [["Anatomy", c.anatomy], ["Variants", c.variants], ["States", c.states], ["Behaviour", c.behaviour], ["Responsive", c.responsive || ""], ["Accessibility", c.a11y || ""], ["Tokens", "`" + c.tokens + "`"]])}
**Do:** ${c.do}

**Don't:** ${c.dont}

**Change log**

${md.table(["Version", "Date", "Change"], m.log)}`; }).join("\n")}`));

out.push(write("docs/patterns/11-patterns.md", `${md.head("11", "Patterns", "Recurring combinations of components and the rules behind them.")}
${G.patterns.map((p) => `## ${p.name}\n\n${md.list(p.rules)}`).join("\n")}`));

out.push(write("docs/patterns/12-dos-and-donts.md", `${md.head("12", "Do's and don'ts", "Quick rules that keep every screen consistent.")}
${md.table(["Topic", "Do", "Don't"], G.usage)}`));

out.push(write("docs/developers/13-tokens-and-setup.md", `${md.head("13", "Tokens and setup", "Every value in this book is a token. Code uses token names, never raw values.")}
## Files

${md.table(["File", "What it is"], [["`tokens/tokens.json`", "Primitives, semantic tokens and scales, as data."], ["`tokens/tokens.css`", "The same values as CSS variables, light and dark."], ["`tokens/components.css`", "Styles for every component (`ds-` classes)."], ["`assets/icons/`", "Every icon as an SVG file, plus a sprite."]])}
## Install

\`\`\`html
${B.fonts.body.google ? `<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=${B.fonts.body.google}&display=swap">\n` : ""}<link rel="stylesheet" href="tokens/tokens.css">
<link rel="stylesheet" href="tokens/components.css">
\`\`\`

Switch any section to dark with \`data-theme="dark"\`.

## Primitive and semantic tokens

Primitives hold raw values. Semantic tokens point to primitives and describe a job. Only semantic tokens appear in components.

## Token naming

Name a token by its job, not its colour.

${md.table(["Family", "Pattern", "Example", "Don't"], G.tokenNaming.map((r) => [r[0], "`" + r[1] + "`", "`" + r[2] + "`", r[3]]))}
## Keep in mind

${md.list(G.keepInMind)}
## Updating the book

1. Edit the \`BRAND\` block in \`index.html\`.
2. Run \`node tools/build.js\`.
3. Add a row to the change log in \`BRAND.changes\` and rebuild.`));

out.push(write("CHANGE-HISTORY.md", `# Change history

${B.name} Brand Book. Edit \`BRAND.changes\` (book) and \`BRAND.components\` (components) in \`index.html\`, then run \`node tools/build.js\`.

## Book change log

Status is Proposed, In review, Approved, Published or Deprecated.

${md.table(["Version", "Date", "Section", "Change", "Reason", "Owner", "Status"], B.changes)}
## Component change log

Component library v${LIB.version}. Component status is Stable, Beta, New, Deprecated or Draft.

${md.table(["Component", "Version", "Date", "Change"], G.components.flatMap((c) => META(c.id).log.map((l) => [c.name, l[0], l[1], l[2]])))}`));

console.log("Built " + B.name + " v" + B.version + ":\n  " + out.join("\n  "));
